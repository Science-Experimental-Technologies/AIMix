import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const registryDir = join(root, "open-sse", "providers", "registry");
const outputPath = join(registryDir, "index.js");
const hiddenProviders = new Map([
  ["devin-cli.js", "spawns local agent with shell/fs access"],
  ["trae.js", "no tool calling"],
  ["windsurf.js", "no tool calling"],
]);

const files = (await readdir(registryDir))
  .filter((name) => name.endsWith(".js") && name !== "index.js")
  .sort((a, b) => a.localeCompare(b));

const imports = files.map((file, index) => {
  const reason = hiddenProviders.get(file);
  return reason
    ? `// import provider${index} from "./${file}"; // hidden: ${reason}`
    : `import provider${index} from "./${file}";`;
});
const entries = files.map((file, index) => {
  const reason = hiddenProviders.get(file);
  return reason ? `  // provider${index}, // ${file.slice(0, -3)} — hidden: ${reason}` : `  provider${index},`;
});
const output = [
  "// Auto-generated by scripts/generate-provider-registry.mjs. Do not edit manually.",
  ...imports,
  "",
  "export default [",
  ...entries,
  "];",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== output) {
    console.error(`${relative(root, outputPath)} is stale. Run npm run generate:providers.`);
    process.exitCode = 1;
  } else {
    console.log(`${relative(root, outputPath)} is current (${files.length} provider files).`);
  }
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`Generated ${relative(root, outputPath)} from ${files.length} provider files.`);
}
